import type { Selector_Candidate } from '../../shared/protocol/wire.ts';

// Finds the most resilient pure CSS selectors of an element: it prefers identity (test hooks, validated
// IDs, ARIA / data attributes) over structure, anchors on the nearest unique ancestor and adds as few
// steps as it can. See docs/SELECTOR.md for the reasoning.
//
// Serialized with toString() and executed inside the web page (see `page_prelude` in web.ts), so
// everything it needs, constants and helpers included, has to live inside the function.
export function resilient_selectors(element: Element): Selector_Candidate[] {
    // ---------- Tuning ----------
    const anchor_min_score = 60;
    const max_anchors = 3;
    // Counts every step, the anchor and the target included
    const max_steps = 5;
    const max_results = 3;
    // The page's own thread runs this, so a slow search must stop instead of freezing the page
    const budget_ms = 150;
    const anchor_distance_penalty = 3;
    const deadline = performance.now() + budget_ms;
    const out_of_time = () => performance.now() > deadline;

    interface descriptor {
        css: string;
        score: number;
        signal: string;
        positional?: boolean;
    }
    // `rank` is the index in `ancestors` (nearest first), -1 for the target
    interface step {
        node: Element;
        rank: number;
        desc: descriptor;
    }

    if (element === document.documentElement || element === document.body) {
        return [{ selector: element.localName, confidence: 100, signals: ['tag'] }];
    }

    // ---------- Vocabulary ----------
    const test_hooks = ['data-testid', 'data-test', 'data-test-id', 'data-qa', 'data-cy', 'data-automation-id', 'data-e2e'];
    // State, framework noise and presentation: they change while the user works or between builds
    const noisy_data_names = new Set([
        'data-state', 'data-status', 'data-headlessui-state', 'data-index', 'data-key', 'data-orientation', 'data-side',
        'data-align', 'data-placement', 'data-size', 'data-variant', 'data-disabled', 'data-open', 'data-checked',
        'data-selected', 'data-active', 'data-loading', 'data-expanded', 'data-focus', 'data-hover', 'data-highlighted',
        'data-pressed', 'data-focus-visible',
    ]);
    const noisy_data_prefixes = ['data-v-', 'data-radix-', 'data-emotion', 'data-rr-', 'data-styled', 'data-n-', 'data-react', 'data-ember', 'data-sentry'];
    const state_class = /^(?:active|open|opened|closed|selected|focus|focused|focus-visible|focus-within|hover|hovered|disabled|checked|current|expanded|collapsed|show|shown|visible|loading|loaded|enabled|pressed|dirty|touched|untouched|pristine|valid|invalid|is-.+|has-.+|ng-.+|.+-(?:active|open|opened|selected|focused|hover|disabled|checked|expanded|collapsed|loading))$/i;
    // Tailwind style utilities say how something looks, which is what a redesign changes
    const utility_class = /^(?:-?(?:[mp][xytblr]?|[wh]|size|gap(?:-[xy])?|space-[xy]|inset(?:-[xy])?|top|right|bottom|left|z|text|bg|border(?:-[xytblr])?|rounded|shadow|opacity|font|leading|tracking|flex|grid|col|row|order|basis|grow|shrink|min-[wh]|max-[wh]|overflow(?:-[xy])?|items|justify|self|place-\w+|content|object|cursor|transition|duration|ease|delay|animate|ring|outline|fill|stroke|divide|align|whitespace|break|line-clamp|aspect|columns|float|clear|select|resize|sr)(?:-[\w./%#[\]-]+)?|flex|grid|block|inline|inline-block|inline-flex|hidden|relative|absolute|fixed|sticky|static|truncate|container|italic|underline|uppercase|lowercase|capitalize|invisible|contents|table|group|peer)$/;
    // Values that are known to be generated by libraries and build tools
    const known_generated = [
        /^:r[0-9a-z]+:$/i,
        /^(?:ember|react-select|mui|rc|ui-id)[-_:]?\d+/i,
        /^(?:radix|headlessui)[-_:]/i,
        /[0-9a-f]{8}-[0-9a-f]{4}-/i,
        /^(?:css|sc|jsx|svelte|emotion|tw)-[\w-]+$/i,
        /^[a-f0-9]{8,}$/i,
        /\d{4,}/,
        /^_[A-Za-z0-9_-]{5,}$/,
    ];
    // Button_primary__3xK9a: a readable part and a hashed suffix
    const css_module = /^((?:[A-Za-z][A-Za-z0-9-]*)_(?:[A-Za-z][A-Za-z0-9-]*)__)[A-Za-z0-9_-]{4,}$/;

    // ---------- Is a value generated? ----------
    const entropy = (text: string): number => {
        const frequency = new Map<string, number>();
        for (const character of text) frequency.set(character, (frequency.get(character) ?? 0) + 1);
        let bits = 0;
        for (const total of frequency.values()) {
            const share = total / text.length;
            bits -= share * Math.log2(share);
        }
        return bits;
    };

    const is_generated = (value: string, kind: 'id' | 'class' | 'attr'): 'reject' | 'penalize' | 'accept' => {
        if (!value || value.length > 64) return 'reject';
        if (known_generated.some((pattern) => pattern.test(value))) return 'reject';
        let has_trailing_digits = false;
        let words = 0;
        let total = 0;
        for (const segment of value.split(/[-_:.\s[\]/]+/).filter(Boolean)) {
            const case_flips = (segment.match(/[a-z][A-Z]/g) ?? []).length;
            if (segment.length >= 6 && case_flips >= 3 && segment.length / (case_flips + 1) < 3) return 'reject';
            for (let token of segment.replace(/([a-z])([A-Z])/g, '$1 $2').split(' ')) {
                // step2 and col-6 are often positions: allowed, but worth less
                if (/^\d{1,3}$/.test(token)) {
                    has_trailing_digits = true;
                    continue;
                }
                if (/^[a-z]+\d{1,3}$/i.test(token)) {
                    has_trailing_digits = true;
                    token = token.replace(/\d+$/, '');
                }
                total++;
                const digits = (token.match(/\d/g) ?? []).length;
                if (digits / token.length > 0.3) return 'reject';
                if (token.length >= 8 && entropy(token) > 3.5) return 'reject';
                if (/^[a-z]+$/i.test(token)) {
                    const vowels = (token.match(/[aeiouy]/gi) ?? []).length;
                    if (token.length >= 5 && vowels === 0) return 'reject';
                    if (token.length >= 7 && (vowels / token.length < 0.1 || vowels / token.length > 0.7)) return 'reject';
                    if (token.length >= (kind === 'attr' ? 1 : 2)) words++;
                }
            }
        }
        if (total === 0 || words / total < 0.6) return 'reject';
        return has_trailing_digits ? 'penalize' : 'accept';
    };

    // Natural language labels: a counter, a price or a name makes them change with the content
    const looks_dynamic = (text: string): boolean => text.length === 0 || text.length > 60 || /\d|[$€£¥%{}]/.test(text);

    const quote = (value: string): string => `"${value.replace(/[\\"]/g, '\\$&').replace(/\n/g, '\\a ')}"`;
    const attribute_css = (name: string, value: string): string => (value === '' ? `[${CSS.escape(name)}]` : `[${CSS.escape(name)}=${quote(value)}]`);

    // ---------- Descriptors of one node ----------
    const attribute_descriptors = (node: Element): descriptor[] => {
        const found: descriptor[] = [];
        const add = (name: string, value: string, score: number, verdict: 'penalize' | 'accept', css = attribute_css(name, value)) => {
            found.push({ css, score: verdict === 'penalize' ? score - 15 : score, signal: name });
        };
        for (const hook of test_hooks) {
            const value = node.getAttribute(hook);
            const verdict = value ? is_generated(value, 'attr') : 'reject';
            if (value && verdict !== 'reject') add(hook, value, 100, verdict);
        }
        if (node.id) {
            const verdict = is_generated(node.id, 'id');
            if (verdict !== 'reject') add('id', node.id, 95, verdict, `#${CSS.escape(node.id)}`);
        }
        const name = node.getAttribute('name');
        if (name) {
            const verdict = is_generated(name, 'attr');
            if (verdict !== 'reject') add('name', name, 85, verdict);
        }
        const label = node.getAttribute('aria-label');
        if (label && !looks_dynamic(label)) add('aria-label', label, 85, 'accept');
        for (const attribute of node.getAttributeNames()) {
            if (!attribute.startsWith('data-') || test_hooks.includes(attribute) || noisy_data_names.has(attribute)) continue;
            if (noisy_data_prefixes.some((prefix) => attribute.startsWith(prefix))) continue;
            const value = node.getAttribute(attribute) ?? '';
            // A bare attribute such as data-cds is an identity on its own
            if (value === '') {
                add(attribute, value, 80, 'accept');
                continue;
            }
            if (value.length > 60 || /^(?:true|false|on|off|yes|no|null|undefined|0|1)$/i.test(value)) continue;
            const verdict = is_generated(value, 'attr');
            if (verdict !== 'reject') add(attribute, value, 80, verdict);
        }
        const role = node.getAttribute('role');
        if (role && /^[a-z-]{1,30}$/.test(role)) add('role', role, 60, 'accept');
        for (const attribute of ['placeholder', 'alt', 'title']) {
            const value = node.getAttribute(attribute);
            if (value && !looks_dynamic(value)) add(attribute, value, 60, 'accept');
        }
        const href = node.getAttribute('href');
        if (href && ['a', 'area'].includes(node.localName)) {
            // Only the path: a query string or an ID in it changes between visits
            const is_absolute = /^[a-z][a-z\d+.-]*:\/\//i.test(href);
            const path = href.replace(/[?#].*$/, '').replace(/^[a-z][a-z\d+.-]*:\/\/[^/]*/i, '');
            const segments = path.split('/').filter(Boolean);
            if (/^\/./.test(path) && segments.every((segment) => is_generated(segment, 'attr') !== 'reject')) {
                const css = is_absolute ? `[href*=${quote(path)}]` : path === href ? attribute_css('href', href) : `[href^=${quote(path)}]`;
                add('href', path, 60, 'accept', css);
            }
        }
        const type = node.getAttribute('type');
        if (type && /^[a-z-]{1,20}$/.test(type)) add('type', type, 55, 'accept');
        for (const attribute of ['aria-labelledby', 'aria-describedby']) {
            const value = node.getAttribute(attribute);
            if (value && value.split(/\s+/).every((id) => is_generated(id, 'id') !== 'reject')) add(attribute, value, 50, 'accept');
        }
        return found.sort((a, b) => b.score - a.score);
    };

    const class_descriptors = (node: Element): descriptor[] => {
        const found: descriptor[] = [];
        for (const name of Array.from(node.classList)) {
            const module_match = css_module.exec(name);
            if (module_match) {
                if (is_generated(module_match[1].replace(/__$/, ''), 'class') !== 'reject') {
                    found.push({ css: `[class*=${quote(module_match[1])}]`, score: 10, signal: 'class-module' });
                }
                continue;
            }
            if (/[:[\]/]/.test(name) || state_class.test(name) || utility_class.test(name)) continue;
            const verdict = is_generated(name, 'class');
            if (verdict !== 'reject') found.push({ css: `.${CSS.escape(name)}`, score: verdict === 'penalize' ? 5 : 10, signal: 'class' });
        }
        return found;
    };

    // Only the target gets these: its position is what the person picked, an ancestor's position is
    // layout they never saw
    const positional_descriptors = (node: Element): descriptor[] => {
        const tag = CSS.escape(node.localName);
        const siblings = node.parentElement ? Array.from(node.parentElement.children) : [node];
        const same_tag = siblings.filter((sibling) => sibling.localName === node.localName);
        const child = siblings.indexOf(node) + 1;
        const of_type = same_tag.indexOf(node) + 1;
        const list: [string, number, string][] = [];
        if (child === 1) list.push([':first-child', 25, 'first-child']);
        if (child === siblings.length) list.push([':last-child', 25, 'last-child']);
        if (of_type === 1) list.push([':first-of-type', 25, 'first-of-type']);
        if (of_type === same_tag.length) list.push([':last-of-type', 25, 'last-of-type']);
        list.push([`:nth-last-of-type(${same_tag.length - of_type + 1})`, 20, 'nth-last-of-type']);
        list.push([`:nth-of-type(${of_type})`, 18, 'nth-of-type']);
        list.push([`:nth-child(${child})`, 12, 'nth-child']);
        return list.map(([pseudo, score, signal]) => ({ css: tag + pseudo, score, signal: `tag+${signal}`, positional: true }));
    };

    // Try order, simplest first: [attr], tag[attr], tag[a][b], tag, class
    const candidate_cache = new Map<Element, descriptor[]>();
    const candidates = (node: Element): descriptor[] => {
        const known = candidate_cache.get(node);
        if (known) return known;
        const tag = CSS.escape(node.localName);
        const is_body = node === document.body;
        const attributes = attribute_descriptors(node);
        const list: descriptor[] = attributes.slice(0, 5);
        if (!is_body) {
            for (const attribute of attributes.slice(0, 3)) {
                if (attribute.signal !== 'id') list.push({ css: tag + attribute.css, score: attribute.score, signal: attribute.signal });
            }
            const top = attributes.filter((attribute) => attribute.signal !== 'id').slice(0, 3);
            for (let first = 0; first < top.length; first++) {
                for (let second = first + 1; second < top.length; second++) {
                    list.push({
                        css: tag + top[first].css + top[second].css,
                        score: Math.min(100, Math.min(top[first].score, top[second].score) + 5),
                        signal: `${top[first].signal}+${top[second].signal}`,
                    });
                }
            }
            list.push({ css: tag, score: 30, signal: 'tag' });
            list.push(...class_descriptors(node).slice(0, 2));
        }
        const seen = new Set<string>();
        const unique = list.filter((desc) => !seen.has(desc.css) && seen.add(desc.css));
        candidate_cache.set(node, unique);
        return unique;
    };

    // ---------- Matching ----------
    const count_cache = new Map<string, number>();
    const count = (selector: string): number => {
        const known = count_cache.get(selector);
        if (known !== undefined) return known;
        let total = Infinity;
        try {
            total = document.querySelectorAll(selector).length;
        } catch {
            // An invalid selector never matches anything useful
        }
        count_cache.set(selector, total);
        return total;
    };
    const verify = (selector: string): boolean => {
        try {
            const hits = document.querySelectorAll(selector);
            return hits.length === 1 && hits[0] === element;
        } catch {
            return false;
        }
    };
    const css_of = (steps: step[]): string => steps.slice().sort((a, b) => b.rank - a.rank).map((item) => item.desc.css).join(' ');

    // ---------- Results ----------
    const ancestors: Element[] = [];
    for (let node = element.parentElement; node && node !== document.documentElement; node = node.parentElement) ancestors.push(node);

    const pool: { result: Selector_Candidate; first_node: Element; target_signals: string[]; length: number }[] = [];
    const add_result = (steps: step[], anchor_distance: number): void => {
        const ordered = steps.slice().sort((a, b) => b.rank - a.rank);
        const selector = ordered.map((item) => item.desc.css).join(' ');
        if (pool.some((entry) => entry.result.selector === selector) || !verify(selector)) return;
        const average = ordered.reduce((sum, item) => sum + item.desc.score, 0) / ordered.length;
        const confidence = average - 4 * (ordered.length - 1) - (ordered.some((item) => item.desc.positional) ? 15 : 0) - (anchor_distance > 4 ? 10 : 0);
        pool.push({
            result: { selector, confidence: Math.round(Math.max(0, Math.min(100, confidence))), signals: ordered.map((item) => item.desc.signal) },
            first_node: ordered[0].node,
            target_signals: ordered[ordered.length - 1].desc.signal.split('+'),
            length: ordered.length,
        });
    };

    // 1. The target on its own
    const target_candidates = candidates(element);
    for (const desc of target_candidates) {
        if (count(desc.css) === 1) add_result([{ node: element, rank: -1, desc }], 0);
    }

    // 2. Ancestors that identify themselves, the nearest and strongest first
    interface anchor {
        step: step;
        distance: number;
    }
    const anchors: anchor[] = [];
    ancestors.forEach((node, index) => {
        for (const desc of candidates(node)) {
            if (desc.score >= anchor_min_score && count(desc.css) === 1) {
                anchors.push({ step: { node, rank: index, desc }, distance: index + 1 });
                break;
            }
        }
    });
    anchors.sort((a, b) => b.step.desc.score - anchor_distance_penalty * b.distance - (a.step.desc.score - anchor_distance_penalty * a.distance));

    // 3. Grow a selector from an anchor towards the target, one step at a time
    // `banned` holds signals of results found already: a pass that bans them can only find a result built
    // from something else, which is what makes a fallback worth having
    const grow = (anchor: anchor | null, banned: Set<string>): void => {
        const own = target_candidates.filter((desc) => !desc.signal.split('+').some((signal) => banned.has(signal)));
        if (own.length === 0) return;
        const steps: step[] = anchor ? [anchor.step] : [];
        const between = ancestors.slice(0, anchor ? anchor.step.rank : ancestors.length);
        const as_target = (desc: descriptor): step => ({ node: element, rank: -1, desc });

        const find_target = (): step | null => {
            for (const desc of own) {
                if (count(css_of([...steps, as_target(desc)])) === 1) return as_target(desc);
                if (out_of_time()) break;
            }
            return null;
        };

        let found = find_target();
        while (!found && steps.length < max_steps - 1 && !out_of_time()) {
            const current = count(css_of([...steps, as_target(own[0])]));
            let best: { step: step; matches: number } | null = null;
            for (const [rank, node] of between.entries()) {
                if (steps.some((item) => item.node === node)) continue;
                for (const desc of candidates(node)) {
                    const matches = count(css_of([...steps, { node, rank, desc }, as_target(own[0])]));
                    if (matches >= current || matches < 1) continue;
                    const is_better =
                        !best ||
                        matches < best.matches ||
                        (matches === best.matches && (desc.score > best.step.desc.score || (desc.score === best.step.desc.score && rank < best.step.rank)));
                    if (is_better) best = { step: { node, rank, desc }, matches };
                }
                if (out_of_time()) break;
            }
            if (!best) break;
            steps.push(best.step);
            found = find_target();
        }

        // Still ambiguous: the target's own position is the last thing to try
        if (!found && banned.size === 0) {
            for (const desc of positional_descriptors(element)) {
                if (count(css_of([...steps, as_target(desc)])) === 1) {
                    found = as_target(desc);
                    break;
                }
            }
        }
        if (!found) return;

        // Prune: a step the selector does not need is a dependency on a layout that may change. The anchor
        // included: it is where the search started, not something the result owes anything to
        let chain = [...steps, found];
        // A position only means something inside its group ("the 3rd button of this form"), so a positional
        // target keeps the scope it was found with, and gets one when it has none
        if (found.desc.positional && steps.length === 0) {
            const scope = ancestors.find((node) => candidates(node).length > 0);
            if (scope) chain = [{ node: scope, rank: ancestors.indexOf(scope), desc: candidates(scope)[0] }, found];
        }
        for (const item of found.desc.positional ? [] : [...chain]) {
            if (item === found) continue;
            const without = chain.filter((other) => other !== item);
            if (count(css_of(without)) === 1) chain = without;
        }
        // The steps left may now allow a stronger descriptor than the one that was cheapest to find
        chain = chain.map((item) => {
            if (item.node === element || item === anchor?.step) return item;
            const better = candidates(item.node)
                .filter((desc) => desc.score > item.desc.score)
                .sort((a, b) => b.score - a.score)
                .find((desc) => count(css_of(chain.map((other) => (other === item ? { ...item, desc } : other)))) === 1);
            return better ? { ...item, desc: better } : item;
        });
        add_result(chain, anchor && chain.includes(anchor.step) ? anchor.distance : 0);
    };

    const top_anchors = anchors.slice(0, max_anchors);
    for (const anchor of top_anchors) {
        if (out_of_time()) break;
        grow(anchor, new Set());
    }
    if (pool.length === 0 && !out_of_time()) grow(null, new Set());

    // Fallbacks: search again without the signals that already worked
    const banned = new Set<string>();
    for (let pass = 0; pass < 2 && pool.length > 0 && !out_of_time(); pass++) {
        const before = pool.length;
        for (const entry of pool) for (const signal of entry.target_signals) if (signal !== 'tag') banned.add(signal);
        for (const anchor of top_anchors) {
            if (out_of_time()) break;
            grow(anchor, banned);
        }
        if (pool.length === before) break;
    }

    // 4. Nothing identifies it: an exact structural path, flagged as fragile
    if (pool.length === 0) {
        const parts: string[] = [];
        for (let node: Element | null = element; node && node !== document.documentElement; node = node.parentElement) {
            const siblings = node.parentElement ? Array.from(node.parentElement.children) : [node];
            const same_tag = siblings.filter((sibling) => sibling.localName === node!.localName);
            const tag = CSS.escape(node.localName);
            parts.unshift(same_tag.length === 1 ? tag : `${tag}:nth-of-type(${same_tag.indexOf(node) + 1})`);
            const selector = parts.join(' > ');
            if (verify(selector)) return [{ selector, confidence: 5, signals: ['structural'] }];
        }
        return [];
    }

    // Best first. A fallback has to differ from the ones before it in its anchor or in what identifies its
    // target, not just in a tag or an extra step, so it still works when the primary's signal is gone
    pool.sort((a, b) => b.result.confidence - a.result.confidence || a.length - b.length || a.result.selector.length - b.result.selector.length);
    const chosen: typeof pool = [];
    for (const entry of pool) {
        if (chosen.length >= max_results) break;
        const is_repeat = chosen.some(
            (other) => other.first_node === entry.first_node && other.target_signals.some((signal) => entry.target_signals.includes(signal)),
        );
        if (is_repeat) continue;
        chosen.push(entry);
    }
    return chosen.map((entry) => entry.result);
}
