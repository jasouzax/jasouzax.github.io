/** Header volume, disabled nonmedia controls, mute activity badge and real touch popup. */
import { test, expect, type Page } from "./desk_fixture.ts"

test.use({ hasTouch: true })

async function media(page: Page): Promise<void> {
    const audio = Buffer.alloc(44 + 8000 * 2 * 30)
    audio.write("RIFF", 0); audio.writeUInt32LE(audio.length - 8, 4)
    audio.write("WAVEfmt ", 8); audio.writeUInt32LE(16, 16)
    audio.writeUInt16LE(1, 20); audio.writeUInt16LE(1, 22)
    audio.writeUInt32LE(8000, 24); audio.writeUInt32LE(16000, 28)
    audio.writeUInt16LE(2, 32); audio.writeUInt16LE(16, 34)
    audio.write("data", 36); audio.writeUInt32LE(audio.length - 44, 40)
    await page.locator('.desk_wbox input[type="file"]').first().setInputFiles({ name: "long.wav", mimeType: "audio/wav", buffer: audio })
    await expect(page.locator("audio")).toBeAttached()
}

test("volume disables for text, supports right-click range and keeps mute/level across viewers", async ({ page }) => {
    await page.goto("/desk")
    const button = page.locator(".desk_wbox_head_audio").first()
    await expect(button).toBeDisabled()
    await media(page)
    await expect(button).toBeEnabled()
    await button.click({ button: "right" })
    const range = page.locator(".desk_volume_popup input")
    await expect(range).toBeVisible()
    await range.fill("0.35")
    await expect.poll(() => page.locator("audio").evaluate((audio: HTMLAudioElement) => audio.volume)).toBeCloseTo(.35)
    await page.keyboard.press("Escape")
    await expect(range).toBeHidden()
    await page.getByRole("button", { name: "Play", exact: true }).click()
    const icon = await button.textContent()
    await button.click()
    await expect(button).toHaveAttribute("aria-pressed", "false")
    await expect(button).toHaveAttribute("data-muted-playing", "")
    expect(await button.textContent()).not.toBe(icon)
    await page.locator('.desk_wbox [data-mode="edit"]').click()
    await expect(button).toBeDisabled()
    await page.locator('.desk_wbox [data-mode="view"]').click()
    await expect(button).toBeEnabled()
    await expect.poll(() => page.locator("audio").evaluate((audio: HTMLAudioElement) => [audio.muted, audio.volume])).toEqual([true, .35])
    await page.keyboard.press("Control+Shift+Enter")
    await expect(page.locator(".desk_volume_popup")).toHaveCount(0)
})

test("touch opens the slider without muting and the next mouse click still toggles mute", async ({ page }) => {
    await page.goto("/desk")
    await media(page)
    const button = page.locator(".desk_wbox_head_audio").first()
    await button.tap()
    await expect(page.locator(".desk_volume_popup input")).toBeVisible()
    await expect(button).toHaveAttribute("aria-pressed", "true")
    await page.locator(".desk_volume_popup input").fill("0")
    await expect(button).toHaveAttribute("aria-pressed", "false")
    await page.keyboard.press("Escape")
    await button.click()
    await expect(button).toHaveAttribute("aria-pressed", "true")
    await expect.poll(() => page.locator("audio").evaluate((audio: HTMLAudioElement) => audio.volume)).toBeGreaterThan(0)
})
