import { test, expect } from "@playwright/test"

test("print emulation edits the SVG while PDF output keeps two clean sheets", async ({ page }) => {
    await page.goto("/ja")
    const form = page.locator(".rireki")
    await expect(form.locator('input[aria-label="氏名"]')).toBeAttached()
    await expect(form).toBeHidden()
    await page.emulateMedia({ media: "print" })
    await expect(form).toBeVisible()
    const sheets = form.locator(".rireki_sheet")
    await expect(sheets).toHaveCount(2)
    await expect(sheets.nth(1).locator("svg")).toContainText("Philnits")
    await expect(form.locator('input[aria-label="licences 1 year"]')).toHaveValue("令和8")
    await expect(form.locator('input[aria-label="licences 1 month"]')).toHaveValue("04")
    const name = form.getByRole("textbox", { name: "氏名", exact: true })
    const bounds = await name.boundingBox()
    const sheetBounds = await sheets.first().boundingBox()
    expect(bounds!.x).toBeGreaterThan(sheetBounds!.x + 100)
    expect(bounds!.width).toBeGreaterThan(400)
    await name.fill("編集テスト")
    await expect(sheets.first().locator("svg")).toContainText("編集テスト")
    await form.getByRole("textbox", { name: "history 17 text", exact: true }).fill("追加の学歴")
    await expect(sheets.first().locator("svg")).toContainText("追加の学歴")
    await form.getByRole("textbox", { name: "本人希望", exact: true }).fill("希望条件\n二行目")
    await expect(sheets.nth(1).locator("svg")).toContainText("二行目")
    await form.getByLabel("証明写真を選択").setInputFiles({
        name: "photo.png", mimeType: "image/png",
        buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aH1sAAAAASUVORK5CYII=", "base64"),
    })
    await expect(form.locator(".rf_photo")).toHaveAttribute("href", /^data:image\/png;base64,/)
    await page.screenshot({ path: ".cache/rireki-editor.png", fullPage: true })
    await name.focus()
    await expect(name).toHaveCSS("opacity", "1")
    await page.evaluate(() => dispatchEvent(new Event("beforeprint")))
    await expect(name).toBeHidden()
    await expect(sheets.first().locator("svg")).toContainText("編集テスト")
    const pdf = await page.pdf({ preferCSSPageSize: true })
    expect(pdf.toString("latin1").match(/\/Type\s*\/Page\b/g)).toHaveLength(2)
    await page.evaluate(() => dispatchEvent(new Event("afterprint")))
    await expect(name).toBeVisible()
    await page.emulateMedia({ media: "screen" })
    await expect(form).toBeHidden()
    await page.reload()
    await page.emulateMedia({ media: "print" })
    await expect(form.getByRole("textbox", { name: "氏名", exact: true })).not.toHaveValue("編集テスト")
})
