import { PDFDocument } from "pdf-lib"
import { readFile } from "node:fs/promises"
import { test, expect } from "./desk_fixture.ts"
test("selected-child conversion menu produces resized rotated images and exposes Save", async ({ page }) => {
    await page.goto("/desk")
    const parent = page.locator(".desk_wbox").first()
    const png = await page.evaluate(() => {
        const canvas = document.createElement("canvas"); canvas.width = 20; canvas.height = 10
        const context = canvas.getContext("2d")!; context.fillStyle = "red"; context.fillRect(0, 0, 20, 10)
        return canvas.toDataURL().split(",")[1]
    })
    await parent.locator('input[type="file"]').setInputFiles({ name: "red.png", mimeType: "image/png", buffer: Buffer.from(png, "base64") })
    await parent.locator(".desk_wbox_head_split").click()
    const child = page.locator(".desk_wbox").nth(1), tab = page.locator('.desk_side_tabs_drop[data-path="desk:conversion"]')
    await page.locator("#head_menu > summary").click()
    await expect(tab).toBeVisible(); await tab.locator("summary").click()
    const menu = page.locator(".desk_conversion_menu")
    await menu.getByLabel("Output MIME").selectOption("image/webp")
    await expect(child).toHaveAttribute("data-converted", "image-webp")
    await menu.locator('[name="image_width"]').fill("40")
    await menu.locator('[name="image_rotation"]').fill("90")
    await menu.getByRole("button", { name: "Apply conversion" }).click()
    await expect.poll(async () => child.locator("img").evaluate(async image => {
        await (image as HTMLImageElement).decode(); return [(image as HTMLImageElement).naturalWidth, (image as HTMLImageElement).naturalHeight]
    })).toEqual([20, 40])
    await expect(child.locator(".desk_wbox_head_save")).toBeEnabled()
    await page.screenshot({ path: ".cache/desk-browser-results/conversion-menu.png" })
    await page.locator("#head_menu > summary").click()
    await parent.locator("img").click()
    await expect(tab).toBeHidden()
    await expect(parent.locator("img")).toHaveJSProperty("naturalWidth", 20)
    await page.locator("#head_menu > summary").click()
    await page.locator('.desk_side_tabs_drop[data-path="desk:windows"] > summary').click()
    const windows = page.locator(".desk_windows_menu")
    await windows.getByRole("textbox", { name: "Desktop name", exact: true }).fill("Image conversion")
    await windows.locator('[data-desktop-action="create"]').click()
    await expect(windows.getByRole("status")).toHaveText("Saved desktop: Image conversion")
    await page.reload()
    await expect.poll(async () => page.locator(".desk_wbox").nth(1).locator("img").evaluate(async image => {
        await (image as HTMLImageElement).decode(); return [(image as HTMLImageElement).naturalWidth, (image as HTMLImageElement).naturalHeight]
    })).toEqual([20, 40])
})

test("CSV chains through JSON to TSV and follows unsaved parent edits", async ({ page }) => {
    await page.goto("/desk")
    const parent = page.locator(".desk_wbox").first()
    await parent.locator('input[type="file"]').setInputFiles({ name: "table.csv", mimeType: "text/csv", buffer: Buffer.from("name,note\nAlice,first\n") })
    await parent.locator(".desk_wbox_head_split").click()
    const child = page.locator(".desk_wbox").nth(1)
    await page.locator("#head_menu > summary").click()
    await page.locator('.desk_side_tabs_drop[data-path="desk:conversion"] > summary').click()
    const menu = page.locator(".desk_conversion_menu")
    await menu.getByLabel("Output MIME").selectOption("text/tab-separated-values")
    await expect(menu.locator("[data-conversion-route]")).toHaveText("text/csv → application/json → text/tab-separated-values")
    await expect(child).toHaveAttribute("data-converted", "csv-json,json-tsv")
    await page.locator("#head_menu > summary").click()
    await child.locator('[data-mode="edit"]').click()
    await expect(child.locator(".desk_wbox_body_text_input")).toHaveValue("name\tnote\r\nAlice\tfirst\r\n".replace(/\r/g, ""))
    await parent.locator(".desk_wbox_body_text_input").fill("name,note\nBob,updated\n")
    await expect(child.locator(".desk_wbox_body_text_input")).toHaveValue("name\tnote\nBob\tupdated\n")
    await parent.locator(".desk_wbox_body_text_input").fill('name,note\n"unterminated')
    await expect(child.getByRole("status")).toContainText("Conversion failed")
    await expect(child.locator(".desk_wbox_head_save")).toBeDisabled()
    await parent.locator(".desk_wbox_body_text_input").fill("name,note\nRecovered,valid\n")
    await expect(child.locator(".desk_wbox_body_text_input")).toHaveValue("name\tnote\nRecovered\tvalid\n")
})

test("PDF controls extract reorder rotate and split native pages", async ({ page }) => {
    const source = await PDFDocument.create()
    source.addPage([100, 200]); source.addPage([300, 400]); source.addPage([500, 600])
    await page.goto("/desk")
    const parent = page.locator(".desk_wbox").first()
    await parent.locator('input[type="file"]').setInputFiles({ name: "pages.pdf", mimeType: "application/pdf", buffer: Buffer.from(await source.save()) })
    await parent.locator(".desk_wbox_head_split").click()
    const child = page.locator(".desk_wbox").nth(1)
    await page.locator("#head_menu > summary").click()
    await page.locator('.desk_side_tabs_drop[data-path="desk:conversion"] > summary').click()
    const menu = page.locator(".desk_conversion_menu")
    await menu.getByLabel("Output MIME").selectOption("application/pdf")
    await menu.locator('[name="pdf_pages"]').fill("3,1")
    await menu.locator('[name="pdf_rotation"]').fill("90")
    await menu.locator('[name="pdf_rotate_pages"]').fill("1")
    await menu.getByRole("button", { name: "Apply conversion", exact: true }).click()
    await expect(child.locator('[data-pdf-ready="true"]')).toBeVisible()
    await page.locator("#head_menu > summary").click()
    const pending = page.waitForEvent("download")
    await child.getByRole("link", { name: "Download PDF", exact: true }).click()
    const download = await pending, pdf = await PDFDocument.load(await readFile((await download.path())!))
    expect(pdf.getPages().map(p => [p.getWidth(), p.getHeight(), p.getRotation().angle])).toEqual([[500, 600, 0], [100, 200, 90]])
    await page.locator("#head_menu > summary").click()
    await menu.getByRole("button", { name: "Split into individual pages" }).click()
    await expect(page.locator(".desk_wbox")).toHaveCount(4)
    await expect(page.locator('[data-pdf-ready="true"]')).toHaveCount(4)
})
