test("desk plugins show code lines, toggle hex, preserve binary edits and report missing resources", async ({ page }) => {
    const plugin_scripts: string[] = []
    page.on("request", request => {
        if (/\/assets\/plugins\/.*\.js$/.test(request.url())) plugin_scripts.push(request.url())
    })
    await page.goto("/desk")
    const window = page.locator(".desk_wbox").first()
    await window.locator('input[type="file"]').setInputFiles({ name: "sample.js", mimeType: "application/javascript", buffer: Buffer.from("const answer = 42;\nconsole.log(answer);\n") })
    await expect(window).toHaveAttribute("data-plugin", "code")
    await expect(window.locator(".desk_wbox_body_text_line_dec")).toHaveText("1\n2\n3")
    await expect(window.locator(".desk_wbox_body_text_line_dec")).toBeVisible()
    await expect(window.locator(".tok_keyword").first()).toHaveText("const")
    expect(plugin_scripts).toEqual([])
    await window.screenshot({ path: ".cache/desk-browser-results/code.png" })
    const toggle = window.locator(".desk_wbox_body_text_tog")
    await toggle.locator("summary").click()
    await expect(toggle).toHaveAttribute("open", "")
    await expect(window.locator(".desk_wbox_body_text_hex_input")).toBeVisible()
    await expect(window.locator(".desk_wbox_body_text_hex_input")).toHaveValue(/^63 6f 6e 73 74/)
    await expect(window.getByRole("radio", { name: "View", exact: true })).toBeChecked()
    await window.locator('[data-mode="edit"]').click()
    await expect(window.getByRole("radio", { name: "Edit", exact: true })).toBeChecked()
    await expect(window.getByRole("radio", { name: "View", exact: true })).not.toBeChecked()
    await expect(window).toHaveAttribute("data-plugin", "code")
    await expect(toggle).not.toHaveAttribute("open", "")
    await toggle.locator("summary").click()
    const bytes = window.locator(".desk_wbox_body_text_hex_input")
    await expect(bytes).toBeEnabled()
    await toggle.locator("summary").click()
    await window.locator(".desk_wbox_body_text_input").fill("const updated = 7;\n")
    await expect(window.locator(".desk_wbox_body_text_line_dec")).toHaveText("1\n2")
    await toggle.locator("summary").click()
    await expect(bytes).toHaveValue(/^63 6f 6e 73 74 20 75 70/)
    await bytes.fill("00 ff c3 28")
    await window.locator(".desk_wbox_head_save").click()
    await expect(window.locator(".desk_wbox_head_save")).not.toHaveClass(/is_dirty/)
    await toggle.locator("summary").click()
    await toggle.locator("summary").click()
    await expect(bytes).toHaveValue("00 ff c3 28")
    await bytes.fill("zz")
    await expect(window.locator(".desk_wbox_head_save")).toBeDisabled()
    const path = window.locator(".desk_wbox_head_path")
    await path.fill("pid:1324")
    await path.press("Enter")
    await expect(window.locator(".desk_wbox_body_error")).toBeVisible()
    await expect(window).toHaveAttribute("data-plugin", "default")
    await path.fill("/missing-plugin-resource.txt")
    await path.press("Enter")
    await expect(window.locator(".desk_wbox_body_error")).toContainText("404")
    await path.fill("")
    await path.press("Enter")
    await expect(window.locator('input[type="file"]')).toBeAttached()
    await window.locator('input[type="file"]').setInputFiles({ name: "pixel.svg", mimeType: "image/svg+xml", buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><rect width="20" height="20" fill="red"/></svg>') })
    // The MIME control can override the detected media type.
    await window.locator(".desk_wbox_head_mime summary").click()
    const search = window.locator(".desk_wbox_head_mime input")
    await search.fill("image/png")
    await search.press("Enter")
    await expect(window).toHaveAttribute("data-plugin", "media")
    await expect(window.locator(".desk_wbox_body_media_image")).toBeVisible()
    await window.getByRole("button", { name: "Zoom in", exact: true }).click()
    await expect(window.locator(".desk_wbox_body_media_image")).toHaveCSS("transform", "matrix(1.25, 0, 0, 1.25, 0, 0)")
})

test("a declarative host can add an optional case script and cleans up its actions", async ({ page }) => {
    await page.route("**/assets/plugins.json", async route => {
        const response = await route.fetch()
        const plugins = await response.json()
        plugins.unshift({ id: "custom", version: "1", cases: [{ file: "true", view: "true", mime: "application/javascript,text/javascript", host: "text", script: "/assets/plugins/custom-test.js" }] })
        await route.fulfill({ response, json: plugins })
    })
    await page.route("**/assets/plugins/custom-test.js", route => route.fulfill({ contentType: "application/javascript", body: `
        export function matches({ item }) { return !!item.file }
        export function setup({ item, case: entry }) {
            item.el.dataset.customAction = entry.host
            return () => { delete item.el.dataset.customAction; item.el.dataset.customCleaned = "true" }
        }
    ` }))
    await page.goto("/desk")
    const window = page.locator(".desk_wbox").first()
    await window.locator('input[type="file"]').setInputFiles({ name: "custom.js", mimeType: "application/javascript", buffer: Buffer.from("const sample = 1;\n") })
    await expect(window).toHaveAttribute("data-plugin", "custom")
    await expect(window).toHaveAttribute("data-custom-action", "text")
    await expect(window.locator(".desk_wbox_body_text_line_dec")).toHaveText("1\n2")
    await window.locator('[data-mode="edit"]').click()
    await expect(window).toHaveAttribute("data-plugin", "code")
    await expect(window).toHaveAttribute("data-custom-cleaned", "true")
    await expect(window).not.toHaveAttribute("data-custom-action")
    await expect(window.locator(".desk_wbox_body_text_tog")).not.toHaveAttribute("open", "")
    await window.locator(".desk_wbox_head_path").fill("")
    await window.locator(".desk_wbox_head_path").press("Enter")
    await window.locator('input[type="file"]').setInputFiles({ name: "bytes.bin", mimeType: "application/octet-stream", buffer: Buffer.from([0, 255, 195, 40]) })
    await window.locator('[data-mode="edit"]').click()
    await expect(window).toHaveAttribute("data-plugin", "hex")
    await expect(window.locator(".desk_wbox_body_text_tog")).toHaveAttribute("open", "")
})

