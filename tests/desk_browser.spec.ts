test("BusyBox terminal, shared file manager, cancellation and private persistence", async ({ page }) => {
    const failures: string[] = []
    const wasm_requests: string[] = []
    page.on("pageerror", error => failures.push(error.message))
    page.on("console", message => { if (message.type() === "error") failures.push(message.text()) })
    page.on("request", request => { if (request.url().endsWith(".wasm")) wasm_requests.push(request.url()) })
    await page.goto("/desk")
    await expect.poll(() => page.evaluate(() => crossOriginIsolated)).toBe(true)
    await expect(page.locator('[data-path="/bin/sh"]')).toBeAttached()
    expect(wasm_requests).toHaveLength(0)
    const open = async () => { await page.locator(".desk_wbox_head_path").fill("pid:"); await page.locator(".desk_wbox_head_path").press("Enter") }
    await open()
    const screen = page.locator(".xterm-rows")
    const output = (text: string) => page.locator(".xterm-rows > div").filter({ hasText: new RegExp(`^${text}\\s*$`) }).first()
    await expect(screen).toContainText("user@jasouza:/home/user$")
    await expect(screen.locator(":scope > div").first()).toHaveText("user@jasouza:/home/user$ ")
    await expect(screen).not.toContainText("BusyBox")
    await expect(page.locator(".xterm-viewport")).toHaveCSS("background-color", "rgba(0, 0, 0, 0)")
    expect(await screen.locator(":scope > div").first().locator("span").evaluateAll(spans => new Set(spans.filter(span => span.textContent?.trim()).map(span => getComputedStyle(span).color)).size)).toBeGreaterThanOrEqual(3)
    expect(wasm_requests).toHaveLength(1)
    const send = async (command: string) => { await page.locator(".xterm-helper-textarea").pressSequentially(command); await page.keyboard.press("Enter") }
    await send("hostname; uname -n; echo HOST_OK")
    await expect(output("HOST_OK")).toBeVisible()
    await expect(output("jasouza")).toBeVisible()
    await send("printf 'beta\\nalpha\\n' | sort > /tmp/pipe.txt; cat /tmp/pipe.txt; echo PIPE_OK")
    await expect(output("PIPE_OK")).toBeVisible()
    await expect(page.locator('[data-path="/tmp/pipe.txt"]')).toBeAttached()
    // OPFS has the same bytes written by the shell; /tmp never touches OPFS.
    await send("cp /tmp/pipe.txt /home/user/saved.txt; echo SAVED_OK")
    await expect(output("SAVED_OK")).toBeVisible()
    expect(await page.evaluate(async () => (await (await (await navigator.storage.getDirectory()).getFileHandle("saved.txt")).getFile()).text())).toBe("alpha\nbeta\n")
    await send("sleep 30")
    await page.waitForTimeout(200)
    await page.keyboard.press("Control+c")
    await send("echo INTERRUPT_OK")
    await expect(output("INTERRUPT_OK")).toBeVisible()
    await send("v=kept; while :; do :; done")
    await page.waitForTimeout(200)
    await page.keyboard.press("Control+c")
    await send("echo LOOP_$v")
    await expect(output("LOOP_kept")).toBeVisible()
    await send("sh")
    await page.waitForTimeout(200)
    await send("echo NESTED_OK")
    await expect(output("NESTED_OK")).toBeVisible()
    await page.keyboard.press("Control+d")
    await send("echo PARENT_OK")
    await expect(output("PARENT_OK")).toBeVisible()
    await page.setViewportSize({ width: 1000, height: 700 })
    await send("printf '\\033[?1049hALT_SCREEN\\033[?1049l'; echo ANSI_OK")
    await expect(output("ANSI_OK")).toBeVisible()
    await page.screenshot({ path: ".cache/desk-browser-results/terminal.png" })
    await page.reload()
    await open()
    await expect(screen).toContainText("user@jasouza:/home/user$")
    await send("cat /home/user/saved.txt; test ! -e /tmp/pipe.txt && echo PERSIST_OK")
    await expect(output("PERSIST_OK")).toBeVisible()
    expect(failures).toEqual([])
})
