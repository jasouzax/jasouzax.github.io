test("Media connects audio playback, seeking, volume and speed controls", async ({ page }) => {
    const audio = Buffer.alloc(44 + 16000 * 2)
    audio.write("RIFF", 0); audio.writeUInt32LE(audio.length - 8, 4)
    audio.write("WAVEfmt ", 8); audio.writeUInt32LE(16, 16)
    audio.writeUInt16LE(1, 20); audio.writeUInt16LE(1, 22)
    audio.writeUInt32LE(8000, 24); audio.writeUInt32LE(16000, 28)
    audio.writeUInt16LE(2, 32); audio.writeUInt16LE(16, 34)
    audio.write("data", 36); audio.writeUInt32LE(audio.length - 44, 40)
    await page.goto("/desk")
    const window = page.locator(".desk_wbox").first()
    await window.locator('input[type="file"]').setInputFiles({ name: "silence.wav", mimeType: "audio/wav", buffer: audio })
    await expect(window).toHaveAttribute("data-plugin", "media")
    const seek = window.getByRole("slider", { name: "Seek", exact: true })
    await expect(seek).toBeEnabled()
    await window.getByRole("button", { name: "Play", exact: true }).click()
    await expect(window.getByRole("button", { name: "Pause", exact: true })).toBeVisible()
    await window.getByRole("button", { name: "Pause", exact: true }).click()
    await seek.fill("1")
    await expect.poll(() => window.locator("audio").evaluate((media: HTMLAudioElement) => media.currentTime)).toBeCloseTo(1)
    await window.getByLabel("Volume controls", { exact: true }).click()
    await window.getByRole("slider", { name: "Volume", exact: true }).fill("0.3")
    await expect.poll(() => window.locator("audio").evaluate((media: HTMLAudioElement) => media.volume)).toBeCloseTo(.3)
    await window.getByRole("button", { name: "Mute", exact: true }).click()
    await expect(window.getByRole("button", { name: "Unmute", exact: true })).toHaveAttribute("aria-pressed", "true")
    await window.getByLabel("Volume controls", { exact: true }).click()
    await window.getByLabel("Settings", { exact: true }).click()
    await window.getByLabel("Playback speed", { exact: true }).selectOption("1.5")
    await expect.poll(() => window.locator("audio").evaluate((media: HTMLAudioElement) => media.playbackRate)).toBe(1.5)
})

