test("terminal colors follow light, dark and operating-system theme changes", async ({ page }) => {
    await page.emulateMedia({ colorScheme: "light" })
    await page.goto("/desk")
    await page.locator(".desk_wbox_head_path").fill("pid:")
    await page.locator(".desk_wbox_head_path").press("Enter")
    await expect(page.locator(".xterm-rows")).toContainText("user@jasouza:")
    const input = page.locator(".xterm-helper-textarea")
    await input.pressSequentially("printf 'PLAIN_TEXT\\n'")
    await input.press("Enter")
    const output = page.locator(".xterm-rows > div").filter({ hasText: /^PLAIN_TEXT\s*$/ }).first()
    await expect(output).toBeVisible()
    await expect(page.locator(".xterm-rows")).toHaveCSS("color", "rgb(0, 0, 0)")
    // Pause only the test's cursor animation to inspect its visible color reliably.
    await page.addStyleTag({ content: ".xterm-cursor { animation: none !important; }" })
    const cursor = page.locator(".xterm-cursor-block").first()
    await expect(cursor).toHaveCSS("background-color", "rgb(0, 0, 0)")
    await page.emulateMedia({ colorScheme: "dark" })
    await expect(page.locator(".xterm-rows")).toHaveCSS("color", "rgb(255, 255, 255)")
    await expect(cursor).toHaveCSS("background-color", "rgb(255, 255, 255)")
    await expect(output).toHaveCSS("color", "rgb(255, 255, 255)")
    await page.evaluate(() => {
        const light = document.querySelector<HTMLInputElement>("#theme_state_light")!
        light.checked = true
        light.dispatchEvent(new Event("change", { bubbles: true }))
    })
    await expect(page.locator(".xterm-rows")).toHaveCSS("color", "rgb(0, 0, 0)")
    await expect(cursor).toHaveCSS("background-color", "rgb(0, 0, 0)")
})

