/* Real browser print layout, language isolation, PDF generation and SPA stylesheet changes. */
import { test, expect } from "./desk_fixture.ts"

for (const theme of ["default", "memory"]) test(`blogs print a book and return to interactive reading in ${theme}`, async ({ page }) => {
    await page.addInitScript(theme => localStorage.setItem("jazu_theme", theme), theme)
    await page.goto("/blogs/chaos-theory")
    const book = page.locator(".blog_book")
    await expect(book).toBeHidden()
    await expect(page.locator(".desk")).toBeVisible()
    await page.emulateMedia({ media: "print" })
    await expect(book).toBeVisible()
    await expect(page.locator(".desk")).toBeHidden()
    await expect(page.locator("#head")).toBeHidden()
    await expect(book.locator(".book_cover h1")).toHaveText("Chaos theory, drawn")
    await expect(book.locator("h1")).toHaveCount(1)
    await expect(book.locator(".book_contents a")).toHaveAttribute("href", "#book_chapter_1")
    await expect(book.locator(".book_chapter")).toContainText("logistic map")
    await expect(book).toHaveCSS("overflow", "visible")
    await expect(book).toHaveCSS("color", "rgb(0, 0, 0)")
    const pdf = await page.pdf({ path: `.cache/blog-book-${theme}.pdf`, preferCSSPageSize: true })
    expect(pdf.subarray(0, 5).toString()).toBe("%PDF-")
    expect(pdf.length).toBeGreaterThan(5000)
    await page.screenshot({ path: `.cache/blog-book-${theme}.png`, fullPage: true })
    await page.emulateMedia({ media: "screen" })
    await expect(book).toBeHidden()
    await expect(page.locator(".desk")).toBeVisible()
    await page.goto("/ja/blogs/chaos-theory")
    await page.emulateMedia({ media: "print" })
    await expect(book.locator(".book_contents h2")).toHaveText("目次")
    await expect(book.locator(".book_cover h1")).toHaveText("カオス理論を描く")
    await expect(book.locator(".book_chapter")).not.toContainText("A short tour")
})
