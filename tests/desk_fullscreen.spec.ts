/** Native fullscreen video overlays and inactivity are reversible by pointer and keyboard. */
import { test, expect } from "./desk_fixture.ts"

test("fullscreen video loses frame decorations and hides idle controls until interaction", async ({ page }) => {
    await page.goto('/desk')
    const pane = page.locator('.desk_wbox').first()
    await pane.locator('input[type="file"]').setInputFiles('content/media/gdsc_demo.mp4')
    const video = pane.locator('video'), head = pane.locator('.desk_wbox_head')
    await expect(video).toBeVisible()
    await pane.getByRole('button', { name: 'Play', exact: true }).click()
    await pane.locator('.desk_wbox_head_fullscreen').click()
    await page.mouse.move(5, 5)
    await expect(pane).toHaveAttribute('data-fullscreen-media', '')
    await expect(pane).toHaveCSS('border-radius', '0px')
    await expect(pane).toHaveCSS('outline-width', '0px')
    await expect(head).toHaveCSS('position', 'absolute')
    await expect(pane).toHaveAttribute('data-media-idle', '')
    await expect(head).toHaveCSS('opacity', '0')
    await page.mouse.move(120, 120)
    await expect(pane).not.toHaveAttribute('data-media-idle', '')
    await expect(head).toHaveCSS('opacity', '1')
    await pane.locator('.desk_wbox_head_audio').click({ button: 'right' })
    const volume = page.locator('.desk_volume_popup:not([hidden]) input')
    await expect(volume).toBeVisible()
    await volume.fill('0.2')
    await expect.poll(() => video.evaluate((video: HTMLVideoElement) => video.volume)).toBeCloseTo(.2)
    await page.keyboard.press('Escape')
    await pane.locator('.desk_wbox_head_fullscreen').focus()
    await page.keyboard.press('Tab')
    await expect.poll(() => pane.locator(':focus-visible').count()).toBeGreaterThan(0)
    await expect(head).toHaveCSS('opacity', '1')
    await page.evaluate(async () => { if (document.fullscreenElement) await document.exitFullscreen() })
    await expect(pane).not.toHaveAttribute('data-fullscreen-media', '')
    await expect(head).not.toHaveCSS('position', 'absolute')
})
