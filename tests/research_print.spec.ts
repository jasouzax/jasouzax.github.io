/** Real print emulation verifies research visibility, complete nested text, PDF output and theme isolation. */
import { test, expect } from "./desk_fixture.ts"

for (const theme of ['default', 'memory']) test(`project printing reveals research and removes the desktop in ${theme}`, async ({ page }) => {
    await page.addInitScript(theme => localStorage.setItem('jazu_theme', theme), theme)
    await page.goto('/projects/stesis')
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    const paper = page.locator('.research_paper')
    await expect(paper).toBeHidden()
    await expect(page.locator('.desk')).toBeVisible()
    await page.emulateMedia({ media: 'print' })
    await expect(paper).toBeVisible()
    await expect(page.locator('.desk')).toBeHidden()
    await expect(page.locator('#head')).toBeHidden()
    await expect(paper.locator('h1')).toHaveText('World Navigation Hat: Wearable AIoT Aid')
    await expect(paper.locator('h2')).toHaveText(['Terminology', 'Problem', 'Solution', 'Significance', 'Objectives', 'Related studies', 'Frameworks', 'Methodology', 'Results'])
    await expect(paper).toContainText('Placeholder:')
    await expect(paper).toContainText('Information gaps')
    await expect(paper).toContainText('replace this prompt with observed needs')
    await expect(paper).toHaveCSS('overflow', 'visible')
    await expect(paper).toHaveCSS('color', 'rgb(0, 0, 0)')
    const pdf = await page.pdf({ path: `.cache/research-paper-${theme}.pdf`, preferCSSPageSize: true })
    expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
    expect(pdf.length).toBeGreaterThan(5000)
    await page.screenshot({ path: `.cache/research-paper-${theme}.png`, fullPage: true })
    await page.emulateMedia({ media: 'screen' })
    await expect(paper).toBeHidden()
    await expect(page.locator('.desk')).toBeVisible()
    await page.goto('/ja/projects/stesis')
    await page.emulateMedia({ media: 'print' })
    await expect(page.locator('.research_paper')).toHaveCount(0)
})
