import { test, expect as base_expect, type Page } from "@playwright/test"
const expect = base_expect.configure({ timeout: 30000 })

async function terminal(page: Page) {
    await page.getByRole("button", { name: "Open terminal", exact: true }).click()
    const screen = page.locator(".xterm-rows")
    await expect(screen).toContainText("user@jasouza:")
    const send = async (command: string) => { await page.locator(".xterm-helper-textarea").pressSequentially(command); await page.keyboard.press("Enter") }
    const line = (value: string) => page.locator(".xterm-rows > div").filter({ hasText: new RegExp(`^${value}\\s*$`) }).last()
    return { screen, send, line }
}

test("real additional WASMs run against the shared browser kernel and filesystem", async ({ page }) => {
    test.setTimeout(180000)
    const failures: string[] = [], wasm: string[] = []
    page.on("pageerror", error => failures.push(error.message))
    page.on("request", request => { if (request.url().endsWith(".wasm")) wasm.push(request.url()) })
    await page.goto("/desk")
    const registry = await (await page.request.get("/assets/wasm/manifest.json")).json()
    expect(registry.map((image: { id: string }) => image.id)).toEqual(["busybox", "fastfetch", "htop", "tcc"])
    for (const image of registry) expect((await page.request.get(image.worker)).headers()["cross-origin-embedder-policy"]).toBe("require-corp")
    expect(wasm).toHaveLength(0)
    const { screen, send, line } = await terminal(page)
    await send("whoami; id; echo IDENTITY_OK")
    await expect(line("IDENTITY_OK")).toBeVisible()
    await expect(line("user")).toBeVisible()
    await expect(screen).toContainText("uid=1000(user)")
    await send("fastfetch --version; fastfetch --logo none --structure OS:Kernel:Uptime:CPU:Memory --pipe true; echo FASTFETCH_OK")
    await expect(line("FASTFETCH_OK")).toBeVisible({ timeout: 30000 })
    await expect(screen).toContainText("2.40.4")
    await expect(screen).toContainText("Jazu Browser Desktop")
    await send("htop --version; echo HTOP_VERSION_OK")
    await expect(line("HTOP_VERSION_OK")).toBeVisible()
    await expect(screen).toContainText("3.4.1")
    await send("htop")
    await expect(screen).toContainText("Tasks:", { timeout: 15000 })
    await expect(screen).toContainText("htop")
    await page.screenshot({ path: ".cache/desk-browser-results/htop-browser.png" })
    await page.locator(".xterm-helper-textarea").pressSequentially("q")
    await expect(screen).toContainText("user@jasouza:/home/user$")
    await send("echo HTOP_EXIT_OK")
    await expect(line("HTOP_EXIT_OK")).toBeVisible()
    await send("printf '#include <stdio.h>\\nint hello(int x) { return x + 7; }\\n' > /home/user/hello.c; tcc -c /home/user/hello.c -o /home/user/hello.o; echo TCC_STATUS_$?")
    await expect(line("TCC_STATUS_0")).toBeVisible({ timeout: 30000 })
    expect(await page.evaluate(async () => [...new Uint8Array(await (await (await (await navigator.storage.getDirectory()).getFileHandle("hello.o")).getFile()).slice(0, 4).arrayBuffer())])).toEqual([0x7f, 69, 76, 70])
    expect(wasm.filter(url => /fastfetch-/.test(url))).toHaveLength(1)
    expect(wasm.filter(url => /htop-/.test(url))).toHaveLength(1)
    expect(wasm.filter(url => /tcc-/.test(url))).toHaveLength(1)
    expect(failures).toEqual([])
})

test("su changes real process credentials and only home file changes survive reload", async ({ page }) => {
    test.setTimeout(180000)
    await page.goto("/desk")
    await page.evaluate(async () => {
        const writer = await (await (await navigator.storage.getDirectory()).getFileHandle("hello.txt", { create: true })).createWritable()
        await writer.write("persistent before deletion"); await writer.close()
    })
    const { screen, send, line } = await terminal(page)
    await send("rm -rf /srv 2>/tmp/denied; test -d /srv && echo USER_DENIED")
    await expect(line("USER_DENIED")).toBeVisible()
    await send("su root -c 'whoami; id; rm -rf /srv; mkdir /root/session-only; echo transient > /etc/browser-session; rm /home/user/hello.txt; echo ROOT_MUTATION_OK'")
    await expect(line("ROOT_MUTATION_OK")).toBeVisible({ timeout: 20000 })
    await expect(line("root")).toBeVisible()
    await expect(screen).toContainText("uid=0(root)")
    await send("whoami; test ! -d /srv && test ! -f /home/user/hello.txt && echo BEFORE_REFRESH_OK")
    await expect(line("BEFORE_REFRESH_OK")).toBeVisible()
    await expect(line("user")).toBeVisible()
    await send('su root -c \'useradd -m guest; su guest -c "whoami; touch /home/guest/note"; echo GUEST_OK\'')
    await expect(line("GUEST_OK")).toBeVisible({ timeout: 15000 })
    await expect(line("guest")).toBeVisible()
    await page.reload()
    const after = await terminal(page)
    await after.send("test -d /srv && test ! -e /etc/browser-session && test ! -e /root/session-only && test ! -f /home/user/hello.txt && echo PERSISTENCE_OK")
    await expect(after.line("PERSISTENCE_OK")).toBeVisible()
    await after.send("whoami; id")
    await expect(after.line("user")).toBeVisible()
    await expect(after.screen).toContainText("uid=1000(user)")
})
