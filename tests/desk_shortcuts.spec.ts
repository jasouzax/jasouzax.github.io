import { test, expect, type Locator } from "@playwright/test"

async function open(window: Locator, path: string) {
    const input = window.locator(".desk_wbox_head_path")
    await input.fill(`file://${path}`); await input.press("Enter")
    await expect(input).toHaveValue(`file://${path}`)
}

test("desktop shortcuts create, focus, move, navigate, refresh, save and close windows", async ({ page }) => {
    await page.goto("/desk")
    await page.evaluate(async () => {
        const root = await navigator.storage.getDirectory()
        const writer = await (await root.getFileHandle("shortcuts.txt", { create: true })).createWritable()
        await writer.write("before"); await writer.close()
    })
    const first = page.locator(".desk_wbox").first()
    await open(first, "/home/user")
    await first.locator('.desk_folder_tile[data-path="/home/user/shortcuts.txt"]').click()
    await expect(page.locator(".desk_wbox")).toHaveCount(1)
    await expect(first.locator(".desk_wbox_body_text_input")).toHaveValue("before")
    await first.locator('[data-mode="edit"]').click()
    await first.locator(".desk_wbox_body_text_input").fill("saved with shortcut")
    await page.keyboard.press("Control+s")
    await expect(first.locator(".desk_wbox_head_save")).not.toHaveClass(/is_dirty/)
    expect(await page.evaluate(async () => (await (await (await navigator.storage.getDirectory()).getFileHandle("shortcuts.txt")).getFile()).text())).toBe("saved with shortcut")
    await page.keyboard.press("Alt+ArrowLeft")
    await expect(first).toHaveAttribute("data-plugin", "folder")
    await page.keyboard.press("Alt+ArrowRight")
    await expect(first.locator(".desk_wbox_body_text_input")).toHaveValue("saved with shortcut")
    await page.evaluate(async () => {
        const writer = await (await (await navigator.storage.getDirectory()).getFileHandle("shortcuts.txt")).createWritable()
        await writer.write("refreshed with shortcut"); await writer.close()
    })
    await page.keyboard.press("Control+r")
    await expect(first.locator(".desk_wbox_body_text_input")).toHaveValue("refreshed with shortcut")
    await expect(first.locator('[data-navigation="previous"] span')).toHaveText("\uf060")
    await expect(first.locator('[data-navigation="refresh"] span')).toHaveText("\uf021")
    await expect(first.locator('[data-navigation="forward"] span')).toHaveText("\uf061")
    const crumbs = first.locator(".desk_wbox_head_breadcrumbs"), box = (await crumbs.boundingBox())!
    await crumbs.click({ position: { x: box.width - 8, y: box.height / 2 } })
    const input = first.locator(".desk_wbox_head_path")
    await expect(input).toBeFocused()
    await input.fill("file:///tmp")
    await input.click({ position: { x: 30, y: 8 } })
    await expect(input).toHaveValue("file:///tmp")
    await input.press("Escape")
    await page.keyboard.press("Control+Enter")
    await expect(page.locator(".desk_wbox")).toHaveCount(2)
    const second = page.locator(".desk_wbox").nth(1), secondId = await second.getAttribute("id")
    await expect(second).toHaveClass(/is_focus/)
    await page.keyboard.press("Control+Tab"); await expect(first).toHaveClass(/is_focus/)
    await page.keyboard.press("Control+Shift+Tab"); await expect(second).toHaveClass(/is_focus/)
    // Left/Right swap columns; Down/Up move between rows.
    const original = (await second.boundingBox())!
    const right = original.x
    await page.keyboard.press("Control+ArrowLeft")
    await expect.poll(async () => (await second.boundingBox())!.x).toBeLessThan(right)
    await page.keyboard.press("Control+ArrowRight")
    await expect.poll(async () => (await second.boundingBox())!.x).toBe(right)
    await page.keyboard.press("Control+ArrowDown")
    await expect.poll(async () => (await second.boundingBox())!.y).toBeGreaterThan(original.y + 20)
    await page.keyboard.press("Control+ArrowUp")
    await expect.poll(async () => (await second.boundingBox())!.y < (await first.boundingBox())!.y).toBe(true)
    // Cycling follows the tab DOM order even after layout changes and maximization.
    await page.locator("#head_full").click()
    await page.keyboard.press("Control+Tab"); await expect(first).toHaveClass(/is_focus/); await expect(first).toBeVisible()
    await page.keyboard.press("Control+Shift+Tab"); await expect(second).toHaveClass(/is_focus/); await expect(second).toBeVisible()
    await page.keyboard.press("Control+Shift+Enter")
    await expect(page.locator(`#${secondId}`)).toHaveCount(0)
    await expect(page.locator(".desk_wbox")).toHaveCount(1)
})

test("internal drops open files and folders in blank windows without moving the sources", async ({ page }) => {
    await page.goto("/desk")
    await page.evaluate(async () => {
        const root = await navigator.storage.getDirectory()
        const dir = await root.getDirectoryHandle("drops", { create: true })
        await dir.getDirectoryHandle("child", { create: true })
        const writer = await (await dir.getFileHandle("open.txt", { create: true })).createWritable()
        await writer.write("drop to open"); await writer.close()
    })
    const source = page.locator(".desk_wbox").first()
    await open(source, "/home/user/drops")
    await page.keyboard.press("Control+Enter")
    const target = page.locator(".desk_wbox").nth(1)
    await source.locator('.desk_folder_tile[data-path="/home/user/drops/open.txt"]').dragTo(target.locator(".desk_wbox_body_empty"))
    await expect(target.locator(".desk_wbox_body_text_input")).toHaveValue("drop to open")
    await expect(target).toHaveClass(/is_focus/)
    await expect(source.locator('.desk_folder_tile[data-path="/home/user/drops/open.txt"]')).toBeVisible()
    await target.locator(".desk_wbox_head_path").fill(""); await target.locator(".desk_wbox_head_path").press("Enter")
    await source.locator('.desk_folder_tile[data-path="/home/user/drops/child"]').dragTo(target.locator(".desk_wbox_body_empty"))
    await expect(target.locator(".desk_wbox_head_path")).toHaveValue("file:///home/user/drops/child")
    await expect(target).toHaveAttribute("data-plugin", "folder")
    await target.locator(".desk_wbox_head_path").fill(""); await target.locator(".desk_wbox_head_path").press("Enter")
    await page.locator("#head_menu > summary").click()
    await page.locator('.desk_side_item[data-path="/bin"] > details > summary').click({ position: { x: 60, y: 8 } })
    await page.locator('.desk_side_item[data-path="/bin/cat"] > details > summary').dragTo(target.locator(".desk_wbox_body_empty"))
    await expect(target.locator(".desk_wbox_head_path")).toHaveValue("file:///bin/cat")
    await expect(page.locator(".desk_wbox")).toHaveCount(2)
})

test("folder mutations preserve unrelated preview nodes and binary cards follow the theme", async ({ page }) => {
    await page.goto("/desk")
    await page.evaluate(async () => {
        const dir = await (await navigator.storage.getDirectory()).getDirectoryHandle("stable", { create: true })
        const child = await dir.getDirectoryHandle("mosaic", { create: true })
        const write = async (target: FileSystemDirectoryHandle, name: string, value: Blob | string) => {
            const writer = await (await target.getFileHandle(name, { create: true })).createWritable(); await writer.write(value); await writer.close()
        }
        const canvas = document.createElement("canvas"); canvas.width = 64; canvas.height = 64
        const ctx = canvas.getContext("2d")!; ctx.fillStyle = "#2288ff"; ctx.fillRect(0, 0, 64, 64)
        const image = await new Promise<Blob>(resolve => canvas.toBlob(blob => resolve(blob!), "image/png"))
        await write(dir, "image.png", image); await write(child, "image.png", image)
        await write(dir, "edit.txt", "original"); await write(child, "edit.txt", "original")
        await write(dir, "data.bin", new Blob([new Uint8Array([0, 255, 2])]))
    })
    const folder = page.locator(".desk_wbox").first()
    await open(folder, "/home/user/stable")
    const tile = (name: string) => folder.locator(`.desk_folder_tile[data-path="/home/user/stable/${name}"]`)
    const image = tile("image.png").locator("img"), card = tile("data.bin").locator(".desk_folder_card")
    await expect(image).toBeVisible(); await expect(card).toBeVisible()
    const imageHandle = (await image.elementHandle())!, cardHandle = (await card.elementHandle())!
    const imageUrl = await image.getAttribute("src")
    const light = await card.evaluate(element => getComputedStyle(element).backgroundColor)
    await page.emulateMedia({ colorScheme: "dark" })
    await expect.poll(() => card.evaluate(element => getComputedStyle(element).backgroundColor)).not.toBe(light)
    await expect(card.locator("strong")).toHaveText("BIN")
    const mosaicImage = tile("mosaic").locator(".desk_folder_cover img")
    await expect(mosaicImage).toBeVisible()
    const mosaicHandle = (await mosaicImage.elementHandle())!
    const mutate = async (path: string, operation: "write" | "add" | "delete") => page.evaluate(async ({ path, operation }) => {
        const dir = await (await navigator.storage.getDirectory()).getDirectoryHandle("stable")
        const target = path.endsWith("mosaic") ? await dir.getDirectoryHandle("mosaic") : dir
        if (operation === "delete") await target.removeEntry("new.txt")
        else {
            const writer = await (await target.getFileHandle(operation === "add" ? "new.txt" : "edit.txt", { create: true })).createWritable()
            await writer.write("updated"); await writer.close()
        }
        document.dispatchEvent(new CustomEvent("jazu:fs:changed", { detail: { path } }))
    }, { path, operation })
    await mutate("/home/user/stable", "write")
    await expect(tile("edit.txt").locator(".desk_folder_text")).toContainText("updated")
    await mutate("/home/user/stable", "add"); await expect(tile("new.txt")).toBeVisible()
    await mutate("/home/user/stable", "delete"); await expect(tile("new.txt")).toHaveCount(0)
    await mutate("/home/user/stable/mosaic", "write")
    await expect(tile("mosaic").locator(".desk_folder_text")).toContainText("updated")
    expect(await imageHandle.evaluate(element => element.isConnected)).toBe(true)
    expect(await cardHandle.evaluate(element => element.isConnected)).toBe(true)
    expect(await mosaicHandle.evaluate(element => element.isConnected)).toBe(true)
    await expect(image).toHaveAttribute("src", imageUrl!)
    await page.screenshot({ path: ".cache/desk-browser-results/stable-preview-cards-dark.png" })
})
