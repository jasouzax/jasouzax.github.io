/** Windows tree, hidden tabs/resources, comparison reparenting and fixed-desk management guard. */
import { test, expect } from "./desk_fixture.ts"

test("Windows shows split hierarchy and restores hidden windows from its resource map", async ({ page }) => {
    await page.goto('/desk')
    const parent = page.locator('.desk_wbox').first()
    await parent.locator('input[type="file"]').setInputFiles({ name: 'draft.txt', mimeType: 'text/plain', buffer: Buffer.from('unsaved draft') })
    await expect(parent.locator('textarea.desk_wbox_body_text_input')).toHaveValue('unsaved draft')
    await parent.locator('.desk_wbox_head_split').click()
    const child = page.locator('.desk_wbox').nth(1)
    await child.locator('[data-mode="edit"]').click()
    await expect(child.locator('textarea.desk_wbox_body_text_input')).toHaveValue('unsaved draft')
    await child.locator('textarea.desk_wbox_body_text_input').fill('edited shared draft')
    await expect(parent.locator('textarea.desk_wbox_body_text_input')).toHaveValue('edited shared draft')
    const menu = page.locator('#head_menu')
    if (await menu.getAttribute('open') === null) await menu.locator(':scope > summary').click()
    await page.locator('.desk_side_tabs_drop > summary').filter({ hasText: /^Windows$/ }).click()
    const panel = page.locator('.desk_windows_menu')
    const child_entry = panel.locator('[data-window-id="2"]')
    await expect(panel.locator('[data-window-id="1"] [data-window-id="2"]')).toHaveCount(1)
    await child_entry.locator(':scope > details > summary').click()
    await child_entry.getByRole('button', { name: 'Hide window', exact: true }).click()
    await expect(child).toBeHidden()
    await expect(page.locator('#head_tabs [data-desk-tab="2"]')).toBeHidden()
    await page.keyboard.press('Control+Tab')
    await expect(page.locator('#head_tabs [data-desk-tab="2"]')).toBeHidden()
    await expect(parent).toBeVisible()
    await page.locator('.desk_side_mode').click()
    const node = page.locator('[data-map-id="window:2"]')
    await expect(node).toHaveAttribute('data-hidden-resource', '')
    await node.locator('a').click()
    await expect(child).toBeVisible()
    await expect(page.locator('#head_tabs [data-desk-tab="2"]')).toBeVisible()
    await expect(child.locator('textarea.desk_wbox_body_text_input')).toHaveValue('edited shared draft')
})

test("dropping a window beneath another creates a comparison and rejects ancestor cycles", async ({ page }) => {
    await page.goto('/desk')
    const first = page.locator('.desk_wbox').first()
    await first.locator('input[type="file"]').setInputFiles({ name: 'first.txt', mimeType: 'text/plain', buffer: Buffer.from('same\nsource\n') })
    await page.keyboard.press('Control+Enter')
    const second = page.locator('.desk_wbox').nth(1)
    await second.locator('input[type="file"]').setInputFiles({ name: 'second.txt', mimeType: 'text/plain', buffer: Buffer.from('same\noutput\n') })
    await expect(second.locator('textarea.desk_wbox_body_text_input')).toHaveValue('same\noutput\n')
    const menu = page.locator('#head_menu')
    if (await menu.getAttribute('open') === null) await menu.locator(':scope > summary').click()
    await page.locator('.desk_side_tabs_drop > summary').filter({ hasText: /^Windows$/ }).click()
    const panel = page.locator('.desk_windows_menu')
    const first_head = panel.locator('[data-window-id="1"] > details > summary'), second_head = panel.locator('[data-window-id="2"] > details > summary')
    await second_head.dragTo(first_head)
    await expect(panel.locator('[data-window-id="1"] [data-window-id="2"]')).toHaveCount(1)
    await expect(second.locator('[data-comparison="ready"]')).toBeVisible()
    await expect(second.locator('.desk_diff_added')).toHaveText('output\n')
    await first_head.dragTo(second_head)
    await expect(panel.locator('[data-window-id="1"] [data-window-id="2"]')).toHaveCount(1)
    await expect(panel.locator('[data-window-id="2"] [data-window-id="1"]')).toHaveCount(0)
})

test("fixed desks do not expose the Windows management menu", async ({ page }) => {
    await page.route(/\/desk\/?$/, async route => {
        const response = await route.fetch()
        await route.fulfill({ response, body: (await response.text()).replace('id="desk"', 'id="desk" data-fixed=""') })
    })
    await page.goto('/desk')
    await expect(page.locator('.desk_windows_menu')).toHaveCount(0)
    await expect(page.locator('.desk_side_tabs_drop[data-path="desk:windows"]')).toHaveCount(0)
})

test("portrait Windows menu restores a hidden window and dismisses its overlay", async ({ page }) => {
    await page.setViewportSize({ width: 480, height: 900 })
    await page.goto('/desk')
    await page.keyboard.press('Control+Enter')
    const menu = page.locator('#head_menu')
    if (await menu.getAttribute('open') === null) await menu.locator(':scope > summary').click()
    await page.locator('.desk_side_tabs_drop > summary').filter({ hasText: /^Windows$/ }).click()
    const entry = page.locator('.desk_windows_menu [data-window-id="2"]')
    await entry.locator(':scope > details > summary').click()
    await entry.getByRole('button', { name: 'Hide window', exact: true }).click()
    await expect(page.locator('#head_tabs [data-desk-tab="2"]')).toBeHidden()
    await entry.getByRole('button', { name: 'Show window', exact: true }).click()
    await expect(page.locator('#desk_win_2')).toBeVisible()
    await expect(page.locator('#head_tabs [data-desk-tab="2"]')).toBeVisible()
    await expect(menu).not.toHaveAttribute('open', '')
    await expect(page.locator('.desk > .desk_wbox:visible')).toHaveCount(1)
})
