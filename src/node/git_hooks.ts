/*
 * Push policy and the hook scripts that enforce it inside each bare repository.
 *
 * Entities:
 *   parse_updates(text)         "old new ref" lines git feeds to pre-/post-receive
 *   check_push(...)             pure policy: returns a refusal message or null (pre-receive)
 *   jobs_for_push(...)          pure mapping from accepted updates to queue jobs (post-receive)
 *   sync_repository(config,id)  writes hooks + safety config into one repository (idempotent)
 *   sync_repositories(config)   same for every repository that exists on disk
 *
 * Scope:
 *   Policy:
 *     archived project -> every push refused
 *     `write` role     -> may push branches, never the deploy branch or tags (owners merge)
 *     `owner` / local  -> allowed; non-fast-forward and deletion are blocked by git config, not by this code
 *   Roles arrive as JAZU_ROLE from the transport; a push made on the server itself has none and counts as local.
 *   Hooks run only `hook_main.ts` (plain node, no build step), never repository-supplied code.
 */
import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs"
import { execFileSync } from "node:child_process"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import type { Job } from "./queue.ts"
import { is_active, project_branch, project_branches, project_ids, repository_path, zero_oid } from "./server_config.ts"
import type { Role, Server_Config } from "./server_config.ts"

export type Ref_Update = { old: string, new: string, ref: string }

export function parse_updates(text: string): Ref_Update[] {
    return text.split("\n").map(line => line.trim().split(/\s+/)).filter(parts => parts.length === 3).map(([old, next, ref]) => ({ old, new: next, ref }))
}

export function check_push(config: Server_Config, project: string, role: Role | undefined, updates: Ref_Update[]): string | null {
    if (!is_active(config, project)) return `${project} is archived and no longer accepts pushes`
    if (role === "read") return "this token is read-only"
    if (role !== "write") return null
    const deploy_refs = project_branches(config, project).map(branch => `refs/heads/${branch}`)
    const blocked = updates.find(update => deploy_refs.includes(update.ref) || update.ref.startsWith("refs/tags/"))
    return blocked ? `only owners may update ${blocked.ref}; push a branch and ask an owner to merge it` : null
}

// Only declared deployment branches start pipelines; collaborator review branches never run code here.
export function jobs_for_push(config: Server_Config, project: string, pusher: string, updates: Ref_Update[]): Omit<Job, "id" | "queued_at">[] {
    if (!is_active(config, project)) return []
    const deploy_refs = project_branches(config, project).map(branch => `refs/heads/${branch}`)
    return updates.filter(update => deploy_refs.includes(update.ref) && update.new !== zero_oid).map(update => ({ kind: "push" as const, project, ref: update.ref, old: update.old, commit: update.new, pusher }))
}

function shell_quote(value: string): string { return `'${value.replace(/\\/g, "/").replace(/'/g, `'\\''`)}'` }

function hook_script(config: Server_Config, kind: "pre-receive" | "post-receive", project: string): string {
    const entry = join(dirname(fileURLToPath(import.meta.url)), "hook_main.ts")
    return [
        "#!/bin/sh",
        "# Generated by jazu (src/node/git_hooks.ts) and rewritten on every node start. Edit server.json, not this file.",
        `export JAZU_SERVER_CONFIG=${shell_quote(config.file)}`,
        `exec ${shell_quote(process.execPath)} --disable-warning=ExperimentalWarning ${shell_quote(entry)} ${kind} ${shell_quote(project)}`,
        "",
    ].join("\n")
}

function git(repository: string, args: string[]): void {
    execFileSync("git", ["-C", repository, ...args], { stdio: "ignore", windowsHide: true })
}

// The deploy branch must never be rewritten or deleted: CI/CD trusts its history.
export function sync_repository(config: Server_Config, id: string): boolean {
    const repository = resolve(repository_path(config, id))
    if (!existsSync(join(repository, "HEAD"))) return false
    const hooks = join(repository, "hooks")
    mkdirSync(hooks, { recursive: true })
    for (const kind of ["pre-receive", "post-receive"] as const) {
        const file = join(hooks, kind)
        writeFileSync(file, hook_script(config, kind, id))
        chmodSync(file, 0o755)
    }
    git(repository, ["config", "receive.denyNonFastForwards", "true"])
    git(repository, ["config", "receive.denyDeletes", "true"])
    git(repository, ["config", "core.logAllRefUpdates", "true"])
    if (is_active(config, id)) {
        git(repository, ["config", "jazu.managed", "true"])
        git(repository, ["config", "jazu.branch", project_branch(config, id)])
        git(repository, ["symbolic-ref", "HEAD", `refs/heads/${project_branch(config, id)}`])
    }
    return true
}

export function sync_repositories(config: Server_Config): string[] {
    const ids = project_ids(config)
    for (const id of ids.filter(id => is_active(config, id))) {
        const repository = repository_path(config, id)
        if (existsSync(join(repository, "HEAD"))) continue
        mkdirSync(repository, { recursive: true })
        git(repository, ["init", "--bare", "--quiet"])
        git(repository, ["symbolic-ref", "HEAD", `refs/heads/${project_branch(config, id)}`])
    }
    return [...ids].filter(id => sync_repository(config, id))
}
