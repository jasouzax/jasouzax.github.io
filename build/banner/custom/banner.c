static void print_word(const char *word) {
    for (int row = 0; row < 5; row++) {
        for (const char *p = word; *p; p++) {
            unsigned char c = (unsigned char)toupper((unsigned char)*p);
            unsigned char mask = (c < 128) ? font[c][row] : 0;
            for (int col = 4; col >= 0; col--) {
                putchar((mask & (1 << col)) ? '#' : ' ');
            }
            putchar(' ');
        }
        putchar('\n');
    }
    putchar('\n');
}

int main(int argc, char **argv) {
    if (argc > 1) {
        for (int i = 1; i < argc; i++) {
            print_word(argv[i]);
        }
    } else {
        char buf[256];
        while (scanf("%255s", buf) == 1) {
            print_word(buf);
        }
    }
    fflush(stdout);
    return 0;
}
